import { z } from 'zod';
import type { Allergene } from './allergens.js';
import type { DispositivoClienteDto } from './sedute.js';
import type { ErroreRegola, StatoGiro } from './regole.js';
import type { SezioneMenu } from './schemas/menu.js';
import type { TestoLocalizzato } from './allergens.js';

// ---------- Menu as served to customers (no à la carte prices) ----------

export interface ImmagineDto {
  src240: string;
  src480: string;
  larghezza: number;
  altezza: number;
  anteprima: string;
}

export interface PiattoMenuDto {
  id: string;
  numero: string | null;
  nome: TestoLocalizzato;
  descrizione: TestoLocalizzato;
  categoriaId: string;
  pezzi: number | null;
  immagine: ImmagineDto | null;
  allergeni: Allergene[];
  vegetariano: boolean;
  piccante: boolean;
  senzaGlutine: boolean;
  inFormula: boolean;
  prezzoExtraCent: number | null;
  maxPerPersona: number | null;
  maxPerGiro: number | null;
  gruppoId: string | null;
  disponibile: boolean;
}

export interface CategoriaMenuDto {
  id: string;
  codice: string;
  nome: TestoLocalizzato;
  sezione: SezioneMenu;
}

export interface GruppoMenuDto {
  id: string;
  nome: TestoLocalizzato;
  maxPerPersona: number;
}

export interface MenuDto {
  versione: string;
  categorie: CategoriaMenuDto[];
  gruppi: GruppoMenuDto[];
  piatti: PiattoMenuDto[];
}

// ---------- The customer's view of the session ----------

export interface VoceCarrelloDto {
  piattoId: string;
  dispositivoId: string;
  quantita: number;
}

export interface GiroDto {
  id: string;
  numero: number;
  stato: StatoGiro;
  soloExtra: boolean;
  inviatoIl: string;
  motivoRifiuto: string | null;
  voci: { piattoId: string; quantita: number }[];
}

export interface SedutaClienteDto {
  sedutaId: string;
  /** Server clock, to correct the device clock in countdowns. */
  ora: string;
  tavoli: number[];
  copertiAdulti: number;
  copertiBambini: number;
  formula: {
    nome: TestoLocalizzato;
    piattiPerPersonaPerGiro: number;
    minutiTraGiri: number;
    durataMaxMinuti: number;
    maxGiri: number | null;
  };
  apertaIl: string;
  minutiExtra: number;
  scadeIl: string;
  io: DispositivoClienteDto;
  dispositivi: DispositivoClienteDto[];
  carrello: VoceCarrelloDto[];
  giri: GiroDto[];
}

export const ImpostaVoceSchema = z.object({
  quantita: z.number().int().min(0).max(99),
});
export type ImpostaVoceRichiesta = z.infer<typeof ImpostaVoceSchema>;

export const InviaGiroSchema = z.object({
  /** Generated by the device for each "send": repeating the request never creates a second round. */
  chiaveIdempotenza: z.uuid(),
});
export type InviaGiroRichiesta = z.infer<typeof InviaGiroSchema>;

/** 422 body when a round breaks the rules. */
export interface ErroreGiroDto {
  codice: 'REGOLE_VIOLATE';
  errori: ErroreRegola[];
}
